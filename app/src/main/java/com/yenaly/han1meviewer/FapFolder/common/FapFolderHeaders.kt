package com.yenaly.han1meviewer.FapFolder.common

import okhttp3.Headers

object FapFolderHeaders {

    fun page(): Headers = Headers.Builder()
        .add("accept", FapFolderConstants.ACCEPT_PAGE)
        .add("accept-encoding", FapFolderConstants.ACCEPT_ENCODING)
        .add("accept-language", FapFolderConstants.ACCEPT_LANGUAGE)
        .add("sec-ch-ua", FapFolderConstants.SEC_CH_UA)
        .add("sec-ch-ua-mobile", FapFolderConstants.SEC_CH_UA_MOBILE)
        .add("sec-ch-ua-platform", FapFolderConstants.SEC_CH_UA_PLATFORM)
        .add("sec-fetch-dest", "document")
        .add("sec-fetch-mode", "navigate")
        .add("sec-fetch-site", "none")
        .add("sec-fetch-user", "?1")
        .add("upgrade-insecure-requests", "1")
        .add("user-agent", FapFolderConstants.USER_AGENT_FAPFOLDER)
        .build()

    fun pageSameOrigin(): Headers = Headers.Builder()
        .add("accept", FapFolderConstants.ACCEPT_PAGE)
        .add("accept-encoding", FapFolderConstants.ACCEPT_ENCODING)
        .add("accept-language", FapFolderConstants.ACCEPT_LANGUAGE)
        .add("sec-ch-ua", FapFolderConstants.SEC_CH_UA)
        .add("sec-ch-ua-mobile", FapFolderConstants.SEC_CH_UA_MOBILE)
        .add("sec-ch-ua-platform", FapFolderConstants.SEC_CH_UA_PLATFORM)
        .add("sec-fetch-dest", "document")
        .add("sec-fetch-mode", "navigate")
        .add("sec-fetch-site", "same-origin")
        .add("sec-fetch-user", "?1")
        .add("referer", FapFolderConstants.HEADER_REFERER)
        .add("upgrade-insecure-requests", "1")
        .add("user-agent", FapFolderConstants.USER_AGENT_FAPFOLDER)
        .build()

    fun ajax(): Headers = Headers.Builder()
        .add("accept", FapFolderConstants.ACCEPT_AJAX)
        .add("accept-encoding", FapFolderConstants.ACCEPT_ENCODING)
        .add("accept-language", FapFolderConstants.ACCEPT_LANGUAGE)
        .add("content-type", FapFolderConstants.CONTENT_TYPE_FORM)
        .add("origin", FapFolderConstants.HEADER_ORIGIN)
        .add("referer", FapFolderConstants.HEADER_REFERER)
        .add("sec-ch-ua", FapFolderConstants.SEC_CH_UA)
        .add("sec-ch-ua-mobile", FapFolderConstants.SEC_CH_UA_MOBILE)
        .add("sec-ch-ua-platform", FapFolderConstants.SEC_CH_UA_PLATFORM)
        .add("sec-fetch-dest", "empty")
        .add("sec-fetch-mode", "cors")
        .add("sec-fetch-site", "same-origin")
        .add("user-agent", FapFolderConstants.USER_AGENT_FAPFOLDER)
        .add("x-requested-with", FapFolderConstants.AJAX_REQUESTED_WITH)
        .build()

    fun ajaxSignin(): Headers = Headers.Builder()
        .add("accept", FapFolderConstants.ACCEPT_AJAX)
        .add("accept-encoding", FapFolderConstants.ACCEPT_ENCODING)
        .add("accept-language", FapFolderConstants.ACCEPT_LANGUAGE)
        .add("content-type", FapFolderConstants.CONTENT_TYPE_FORM)
        .add("origin", FapFolderConstants.HEADER_ORIGIN)
        .add("referer", FapFolderConstants.HEADER_REFERER_SIGNIN)
        .add("sec-ch-ua", FapFolderConstants.SEC_CH_UA)
        .add("sec-ch-ua-mobile", FapFolderConstants.SEC_CH_UA_MOBILE)
        .add("sec-ch-ua-platform", FapFolderConstants.SEC_CH_UA_PLATFORM)
        .add("sec-fetch-dest", "empty")
        .add("sec-fetch-mode", "cors")
        .add("sec-fetch-site", "same-origin")
        .add("user-agent", FapFolderConstants.USER_AGENT_FAPFOLDER)
        .add("x-requested-with", FapFolderConstants.AJAX_REQUESTED_WITH)
        .build()

    fun media(): Headers = Headers.Builder()
        .add("accept", "*/*")
        .add("accept-encoding", FapFolderConstants.ACCEPT_ENCODING)
        .add("accept-language", FapFolderConstants.ACCEPT_LANGUAGE)
        .add("referer", FapFolderConstants.HEADER_REFERER)
        .add("user-agent", FapFolderConstants.USER_AGENT_FAPFOLDER)
        .build()

    fun mediaWithRange(startBytes: Long = 0L): Headers = media().newBuilder()
        .set("range", "bytes=$startBytes-")
        .build()
}
